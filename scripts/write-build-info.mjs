import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(root, "src/lib/buildInfo.generated.ts");

function git(args) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

const commitSha =
  process.env.VERCEL_GIT_COMMIT_SHA ??
  git(["rev-parse", "HEAD"]) ??
  "unknown";

const shortSha = commitSha === "unknown" ? "unknown" : commitSha.slice(0, 7);
const rawCommitRef =
  process.env.VERCEL_GIT_COMMIT_REF ??
  git(["rev-parse", "--abbrev-ref", "HEAD"]) ??
  null;
const commitRef = rawCommitRef === "HEAD" ? null : rawCommitRef;
const commitDate =
  commitSha === "unknown" ? null : git(["show", "-s", "--format=%cI", commitSha]);

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/write-build-info.mjs during npm run build.
export const buildInfo = {
  builtAt: ${JSON.stringify(new Date().toISOString())},
  commitSha: ${JSON.stringify(commitSha)},
  shortSha: ${JSON.stringify(shortSha)},
  commitRef: ${JSON.stringify(commitRef)},
  commitDate: ${JSON.stringify(commitDate)},
} as const;
`,
);
